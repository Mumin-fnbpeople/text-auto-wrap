"""Regenerate the synthetic fonts without adding a package dependency.

Run: uv run --no-project --with fonttools python test/support/generate_font_fixtures.py
Then: .tooling/flutter/bin/dart format test/support/narrow_test_font.dart
"""

import base64
import io
from pathlib import Path
import textwrap

from fontTools.feaLib.builder import addOpenTypeFeaturesFromString
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen


def font_bytes(localized=False):
    builder = FontBuilder(1000, isTTF=True)
    chars = "abcdefW "
    names = [".notdef"] + (["a.wide"] if localized else [])
    names += [f"g{ord(char)}" for char in chars]
    builder.setupGlyphOrder(names)
    builder.setupCharacterMap({ord(char): f"g{ord(char)}" for char in chars})
    glyphs = {}
    for name in names:
        pen = TTGlyphPen(None)
        if name not in [".notdef", "g32"]:
            width = 1000 if name == "a.wide" else 500
            pen.moveTo((0, -200))
            pen.lineTo((width, -200))
            pen.lineTo((width, 800))
            pen.lineTo((0, 800))
            pen.closePath()
        glyphs[name] = pen.glyph()
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics(
        {name: (1000 if name == "a.wide" else 500, 0) for name in names}
    )
    builder.setupHorizontalHeader(ascent=800, descent=-200)
    family = "TawLocaleFixture" if localized else "TawNarrowFixture"
    builder.setupNameTable({
        "familyName": family,
        "styleName": "Regular",
        "uniqueFontIdentifier": family,
        "fullName": family,
        "psName": family,
        "version": "Version 1.0",
    })
    builder.setupOS2(
        sTypoAscender=800, sTypoDescender=-200,
        usWinAscent=800, usWinDescent=200,
    )
    builder.setupPost()
    builder.setupMaxp()
    if localized:
        addOpenTypeFeaturesFromString(builder.font, """
            languagesystem DFLT dflt;
            languagesystem latn dflt;
            languagesystem latn TRK;
            feature locl {
                script latn;
                language TRK;
                sub g97 by a.wide;
            } locl;
        """)
    builder.font.recalcTimestamp = False
    builder.font["head"].created = 2082844800
    builder.font["head"].modified = 2082844800
    output = io.BytesIO()
    builder.save(output)
    return output.getvalue()


output = [
    "import 'dart:convert';\nimport 'dart:typed_data';\n\n",
    "// Synthetic fonts, generated by generate_font_fixtures.py.\n",
    "// 1000 units/em, rectangle glyphs, 500-unit advances; Turkish locl uses 1000.\n",
    "// No external font assets or runtime dependencies.\n",
]
for name, localized in [("narrowTestFont", False), ("localeTestFont", True)]:
    output.append(f"ByteData {name}() => ByteData.sublistView(base64Decode(\n")
    encoded = base64.b64encode(font_bytes(localized)).decode()
    output.extend(f"  '{line}'\n" for line in textwrap.wrap(encoded, 76))
    output.append("));\n\n")
Path(__file__).with_name("narrow_test_font.dart").write_text("".join(output))
